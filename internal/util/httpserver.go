package util

import (
	"net/http"
	"time"
)

// NewHTTPServer returns an *http.Server for addr/handler with the
// read/header/write/idle timeouts every listener in this agent must
// carry (a listener without them is open to Slowloris-style stalls).
// Both the metrics and web-UI servers build on it so the values cannot
// drift apart again.
func NewHTTPServer(addr string, handler http.Handler) *http.Server {
	return &http.Server{
		Addr:              addr,
		Handler:           handler,
		ReadTimeout:       10 * time.Second,
		ReadHeaderTimeout: 5 * time.Second,
		WriteTimeout:      30 * time.Second,
		IdleTimeout:       120 * time.Second,
	}
}
